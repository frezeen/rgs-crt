# Explicit override: crt-dual.analog_lcd=1 in batocera.conf -> analog ports
# (VGA/DVI-I) are treated as LCD. Escape hatch for an LCD on VGA at pre-X
# boot, where EDID is unreadable (NVIDIA sysfs = 0 bytes) and 99-crt.conf
# (HorizSync 15-17) would reject the LCD's EDID modes.
_crt_dual_analog_lcd() {
	local _v
	[ -f "$CRT_DUAL_BATOCERA_CONF" ] || return 1
	# The LAST occurrence is the effective value (batocera-settings APPENDS).
	_v=$(grep -E "^crt-dual\.analog_lcd[[:space:]]*=" "$CRT_DUAL_BATOCERA_CONF" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d ' "[:space:]')
	[ "$_v" = "1" ]
}

# Explicit override: crt-dual.crt_output=<port> in batocera.conf -> that
# port is a CONFIRMED CRT (user declaration). For CRTs on pure digital
# ports behind a converter (e.g. physical VGA driven by a DP on
# Intel/HP 800 G5): auto-detection cannot see them (disconnected, no EDID),
# but the user KNOWS where the CRT is. Highest precedence over the cascade.
# CRT_DUAL_CRT_OUTPUT = port (or empty). Not in CRT_KEYS -> persists.
_crt_dual_crt_output() {
	CRT_DUAL_CRT_OUTPUT=""
	[ -f "$CRT_DUAL_BATOCERA_CONF" ] || return 1
	local v
	# The LAST occurrence is the effective value (batocera-settings APPENDS).
	v=$(grep -E "^crt-dual\.crt_output[[:space:]]*=" "$CRT_DUAL_BATOCERA_CONF" 2>/dev/null | tail -1 | cut -d= -f2- | tr -d ' "')
	[ -n "$v" ] || return 1
	CRT_DUAL_CRT_OUTPUT="$v"
	return 0
}

# Analog port with a valid EDID block in xrandr --prop -> it is an LCD
# (CRTs rarely expose EDID over DDC; verified: DVI-I-0 CRT has no EDID).
# Post-X only (needs xrandr --prop). Returns 0 if the output has a valid
# EDID (magic 00ffffffffffff00 on the first line of the block).
_output_has_edid() {
	local props="$1" out="$2" hex
	hex=$(printf '%s\n' "$props" | awk -v o="$out" '
		$0 ~ "^" o " connected" { hit=1; next }
		hit && /^[^ \t]/ { exit }
		hit && /EDID:/ { edid=1; next }
		hit && edid && /^[ \t]+[0-9a-fA-F]+/ { print $1; exit }
	')
	[ -n "$hex" ] && echo "$hex" | grep -q "^00ffffffffffff00"
}

# EDID of an X output: sysfs edid file (kernel) first — the AMD/Intel
# truth. NVIDIA sysfs keeps 0 bytes even for LCDs (verified GTX 970:
# xrandr --prop carries the block) -> the caller falls back to a LAZY
# xrandr --prop, fetched ONCE per detect (not a full scan per output like
# _edid_reclassify used to do — removed 2026-08-12).
_sysfs_edid_present() {
	local f sz
	for f in "$CRT_DUAL_SYSFS"/card*-"$(_drm_connector "$1")"/edid; do
		[ -f "$f" ] || continue
		# sysfs st_size LIES (reports 0 for a 256-byte edid) and the EDID
		# block starts with 0x00 (nulls are stripped by $()) — count the
		# bytes actually READ with wc -c (verified 2026-08-12 AMD).
		sz=$(wc -c <"$f" 2>/dev/null)
		[ -n "$sz" ] && [ "$sz" -gt 0 ] 2>/dev/null && return 0
	done
	return 1
}

# ANY readable sysfs edid in the system = sysfs DDC is trustworthy
# (amd/intel) -> skip the xrandr --prop lazy fallback (GLITCH-class,
# measured 2026-08-12). Only when ALL edid files are empty on read
# (NVIDIA: sysfs edid 0 bytes even for LCDs, verified 2026-08-11) does
# --prop carry the only block. Vendor-independent — works even when
# detect_gpu never ran (selector/apply/remove source display-lib alone).
_sysfs_has_any_edid() {
	local f sz
	for f in "$CRT_DUAL_SYSFS"/card*/edid; do
		[ -f "$f" ] || continue
		sz=$(wc -c <"$f" 2>/dev/null)
		[ -n "$sz" ] && [ "$sz" -gt 0 ] 2>/dev/null && return 0
	done
	return 1
}

# Shared DRM->X mapping for the X name -> sysfs connector lookup (one
# function, both _sysfs_status and the EDID lookup use it — never re-create
# the mapping). NVIDIA: X index = DRM index-1 (X DVI-I-0 =
# DRM DVI-I-1, X DP-0 = DRM DP-1); AMD/Intel: identity (Intel X "HDMI-1" =
# DRM "HDMI-A-1"). The NVIDIA offset is a measured driver fact (GTX 970,
# verified) — the universal rename (type-order pairing, no vendor branch)
# is a separate, test-guarded step.
_drm_connector() {
	local out="$1" type idx drm
	type="${1%-*}" # shortest suffix: "DVI-I-0" -> "DVI-I" (NOT ${1%%-*} — that longest-suffix cut produced "DVI" and the DVI-I) case never matched; masked pre-2026-08-12 while analog classification came from the xrandr listing, exposed by the sysfs-truth rewrite + caught by the harness)
	idx="${1##*-}"
	case "$type" in
	HDMI) drm="HDMI-A-${idx}" ;;
	DVI-I) drm="DVI-I-${idx}" ;;
	*) drm="${type}-${idx}" ;;
	esac
	# FAMILY MAPPING FACT: DRM connector index vs X index (+1 on NVIDIA,
	# measured GTX 970; identity elsewhere). The universal rename is a
	# separate, test-guarded step.
	idx=$((idx + $(_gpu_adapter && _impl_drm_offset)))
	case "$type" in
	HDMI) drm="HDMI-A-${idx}" ;;
	DVI-I) drm="DVI-I-${idx}" ;;
	*) drm="${type}-${idx}" ;;
	esac
	echo "$drm"
}

# Reverse mapping: DRM (sysfs connector) name -> X output name. The inverse
# of _drm_connector() — same single-source rule, kept adjacent: "HDMI-A-1"
# -> "HDMI-1" (kernel "-A-" quirk), NVIDIA DRM DVI-I-1 -> X DVI-I-0
# (index-1). Used by crt-x11-generator.sh for the Disabled-output list:
# the sysfs enumerates EVERY connector (kernel truth — xrandr cannot: the
# current X already hides the Disabled outputs, so a regen from xrandr
# would drop the very options that kill the phantoms, verified 2026-08-12).
_drm_to_x() {
	local drm="$1" type idx
	case "$drm" in
	HDMI-A-*)
		type="HDMI"
		idx="${drm#HDMI-A-}"
		;;
	*)
		type="${drm%-*}"
		idx="${drm##*-}"
		;;
	esac
	# FAMILY MAPPING FACT (mirror of _drm_connector): DRM index vs X index.
	idx=$((idx - $(_gpu_adapter && _impl_drm_offset || echo 0)))
	echo "${type}-${idx}"
}
# ──────────────────────────────────────────────────
# OUTPUT DETECTION — cascade (reliable signal -> presumption as LAST resort)
#
# For every present output, by reliability order:
# 1. Digital (HDMI/DP/DVI-D/eDP) connected + EDID  -> LCD confirmed
# 2. Analog (VGA/DVI-I/CRT) connected + EDID      -> LCD on analog (dynamic)
# 3. Analog connected WITHOUT EDID                -> CRT confirmed (driver senses the cable)
# 4. Analog DISCONNECTED (LAST resort)            -> CRT_PRESUMED: no reliable
# signal; assume CRT (analog port exists) and the TEST (crt_probe,
# post-X) confirms port liveness or rolls back to stock.
#
# 5. Digital connected WITHOUT EDID (only when no analog port) -> CRT_PRESUMED:
# suspected CRT behind a converter (e.g. physical VGA driven by a DP on
# Intel/HP 800 G5). The probe (connected -> hotplug) confirms it.
# 6. Digital DISCONNECTED (only when no analog port) -> CRT_PRESUMED:
# the port is a DP->VGA converter (no EDID -> "disconnected"); the
# probe (640x480 modeset) verifies whether it is drivable.
#
# Gate 5/6: if an analog port (VGA/DVI-I) EXISTS, digitals cannot be CRTs —
# a CRT on digital requires a converter and auto-detect cannot distinguish
# it from an empty port (only the crt-dual.crt_output override applies there).
#
# Variables: CRT_OUTS (confirmed), CRT_PRESUMED_OUTS (presumed), LCD_OUTS.
# The probe (crt_probe) promotes drivable PRESUMED ports to CONFIRMED
# (/tmp/crt-dual-probe-ok -> re-read by detect_outputs): without promotion, a
# presumed port + LCD stays LCD-only (a detached port with
# LCD = empty, not CRT).
# ──────────────────────────────────────────────────
# 15kHz-class ACTIVE modeline on an output = the kernel is outputting a
# CRT timing RIGHT NOW — the one analog signal that cannot go stale.
# NAME classes that count: 640x480i (desktop), 320x240 (240p fallback),
# SR-* (game native). NOT a CRT: the VESA no-sink 640x480@59.94, the
# 54MHz DoubleScan "640x480", the NVIDIA replug @75. On NVIDIA the bare
# shadowed name needs the ACTIVE Interlace flag instead — family fact,
# canonical story lives in src/lib/gpu/nvidia.sh (ModePool shadowing).
_crt_active_15khz() {
	local out="$1" name
	[ -n "$out" ] || return 1
	name=$(_xrandr_active_mode "$out" name) || return 1
	case "$name" in
	640x480i | 320x240 | SR-*) return 0 ;;
	esac
	# NAME match failed -> ask the FAMILY ORACLE for active-mode truth.
	# On NVIDIA the driver exposes the analog CRT interlace under the bare
	# name "640x480" and refuses aliased modelines on the analog port
	# (ModePool shadowing, BadMatch), so the name match above can never
	# fire there: nvidia.sh reads the ACTIVE mode's Interlace flag via
	# --verbose (glitch-FREE on this stack — dce_v6 blips are AMD-only).
	# amd/intel/generic return 1: their desktop modes carry 15kHz names,
	# --verbose stays unreached (keeps the dce_v6 tube glitch-free).
	_gpu_adapter && _impl_crt_active_truth "$out"
}

# Single source of "is this output analog?" — the ONE predicate the
# detection cascade, the mode setters and the watcher guard MUST agree
# on. 2026-08-19: the bug was exactly two re-derivations disagreeing —
# the EDID-garbage->converter gate in _crt_set_15khz_direct treated a
# bare analog CRT (no EDID -> full VESA mode list) as a digital converter
# and refused 480i, while the analog/digital discrimination lower in the
# same function would have called it analog. One helper everywhere
# removes the disagreement class by construction. Accepts an X output
# name ("DVI-I-0") or a DRM connector name ("DVI-I-1") — shortest-
# suffix type cut (${var%-*}).
_output_is_analog() {
	local out="${1:-}"
	[ -n "$out" ] || return 1
	case "${out%-*}" in # shortest suffix: "DVI-I-0" -> "DVI-I"
	DVI-I | VGA | CRT) return 0 ;;
	*) return 1 ;;
	esac
}

detect_outputs() {
	CRT_OUTS=""
	CRT_PRESUMED_OUTS=""
	LCD_OUTS=""
	CRT_OUT=""
	CRT_PRESUMED_OUT=""
	LCD_OUT=""
	_EDID_PROPS_CACHE="" # fresh oracle snapshot per detection cycle

	if [ -n "${DISPLAY:-}" ] && command -v xrandr >/dev/null 2>&1; then
		_detect_outputs_xrandr
		# X is up but xrandr produces no outputs (X down / wrong DISPLAY) ->
		# sysfs fallback: classification must not stay empty
		# (verified live: X dead at boot -> empty PASSO 7 dump).
		if [ -z "$CRT_OUTS$CRT_PRESUMED_OUTS$LCD_OUTS" ]; then
			_detect_outputs_sysfs
		fi
		# KERNEL TRUTH for LCD removal: xrandr's "connected" can be a
		# PHANTOM right after a physical unplug (X lags sysfs by seconds —
		# verified 2026-08-11 friend's Intel UHD 630: LCD detached, sysfs
		# said disconnected, xrandr still listed DP-1 connected -> the
		# watcher applied the DUAL layout with the CRT at +2560 (right of
		# the gone LCD) -> CRT black on screen. The sysfs status is the
		# kernel truth: an LCD output that sysfs reports disconnected is
		# GONE — drop it from LCD_OUTS so the layout goes CRT-only.
		# (CRTs stay: a CRT behind a converter legitimately reports
		# disconnected with no EDID — that is exactly the presumed/probe
		# path. LCDs always have EDID and a real hotplug signal.)
		_detect_filter_lcd_phantom
	else
		# sysfs fallback (pre-X boot, DISPLAY not exported)
		_detect_outputs_sysfs
	fi

	# Post-classify: 7 helpers pure in display-detect.sh (T15.1 slim)
	_detect_apply_override
	_detect_promote_live
	_detect_promote_probe
	_detect_promote_replug
	_detect_demote
	_detect_escape_analog_lcd
	# Recompute the singles (override/promotion/escape may have
	# invalidated them — without this the layout would use the first
	# PRESUMED port).
	CRT_OUT=$(echo "$CRT_OUTS" | awk '{print $1}')
	CRT_PRESUMED_OUT=$(echo "$CRT_PRESUMED_OUTS" | awk '{print $1}')
	LCD_OUT=$(echo "$LCD_OUTS" | awk '{print $1}')

	# State file for non-bash consumers — the SINGLE authoritative
	# role->port mapping (lists AND the resolved singles). Every consumer
	# (watcher _crt_port/_lcd_port, Python selector, diag) reads this one
	# handoff; nobody re-derives "which output is the CRT/LCD" from raw
	# xrandr or re-splits the lists (2026-08-19 #2 consolidation: stale or
	# missing file degrades to env/empty, never to a wrong port). Additive
	# lines — older readers ignoring the singles are unaffected.
	{
		echo "CRT_OUTS=${CRT_OUTS:-}"
		echo "CRT_PRESUMED_OUTS=${CRT_PRESUMED_OUTS:-}"
		echo "LCD_OUTS=${LCD_OUTS:-}"
		echo "CRT_OUT=${CRT_OUT:-}"
		echo "CRT_PRESUMED_OUT=${CRT_PRESUMED_OUT:-}"
		echo "LCD_OUT=${LCD_OUT:-}"
	} >"$CRT_DUAL_STATE_DIR/detect-state" 2>/dev/null || true # state file is advisory; consumers handle absence

	# Classification log (self-sufficient logs)
	echo "CRT-DUAL-DETECT: confirmed=[${CRT_OUTS:-}] presumed=[${CRT_PRESUMED_OUTS:-}] LCD=[${LCD_OUTS:-}]" >&2
}

