# PROBE — the TEST of presumption (last resort)
# Post-X (X active). For every PRESUMED output (detached analog, or
# digital without analog ports — CRT candidate behind a converter):
#
# SYSFS connector state (kernel truth): connected = real hotplug
# -> CRT confirmed. A sysfs-DISCONNECTED port is NEVER promoted.
#
# The old 640x480 modeset test is GONE as evidence — it was wrong on
# dce_v6 (AMD R9 270X, fire-tested 2026-08-12): the driver ACCEPTS any
# modeset into the EMPTY port (the latch — 320x240 accepted with the
# VGA cable out), so "modeset OK" proves nothing about a sink being
# there. Worse, the probe's own modeset leaves the CRTC emitting 480i
# into the empty port, CREATING the live-timing evidence the next
# detect_outputs reads to self-promote the phantom (observed
# 2026-08-13: the stale X config drove 640x480i on the empty DVI-I ->
# "active timing 15kHz-class -> CRT confirmed" -> CRT-only layout ->
# LCD disabled). The modeset discriminates ONLY on drivers that reject
# empty-port modesets (NVIDIA GTX 970) — not universal, so it confirms
# nothing anywhere.
#
# A converter CRT the kernel does not see (DP->VGA active adapter:
# sysfs disconnected, no EDID — the AUX link never trains on dce_v6,
# verified 2026-08-13) is covered by crt-dual.crt_output=<port>: auto-
# detect cannot distinguish a converter from an empty port.
#
# EVIDENCE: ports that PASS are written to /tmp/crt-dual-probe-ok;
# detect_outputs() promotes them to CONFIRMED CRTs (the layout and the
# selector gate must see them — without promotion, presumed+LCD = LCD-only).
# Called by the boot service (PASSO 7) and by diag-dump.sh.
# ──────────────────────────────────────────────────

# FAMILY STATUS ORACLE (adapter contract): presence of an X output as
# the ACTIVE family sees it — sysfs raw on AMD/Intel, X token on NVIDIA
# (see src/lib/gpu/*.sh headers for each family's evidence). Callers:
# promote/demote debounce, digital classification, LCD post-filter.
_sysfs_status() {
	_gpu_adapter || return 1
	_impl_status "$1"
}

# RAW sysfs connector fingerprint ("DVI-I-0:connected HDMI-0:connected ...")
# — the channel AMD/Intel adapters fingerprint; NOT the family oracle
# itself (that is _layout_fingerprint -> _impl_fingerprint).
_sysfp_raw() {
	local _f _drm _x _s _out=""
	for _f in "$CRT_DUAL_SYSFS"/card*-*/status; do
		[ -f "$_f" ] || continue
		_drm=$(basename "$(dirname "$_f")")
		_drm=${_drm#card*-}
		_x=$(_drm_to_x "$_drm" 2>/dev/null) || continue
		[ -n "$_x" ] || continue
		_s=$(cat "$_f" 2>/dev/null | tr -d '[:space:]')
		[ -n "$_s" ] || continue
		_out="$_out $_x:$_s"
	done
	echo "$_out" | tr ' ' '\n' | sort | tr '\n' ' ' | sed 's/^ //'
}

