# Active mode of an X output from xrandr --current (glitch-free: the
# old --query forced a connector re-probe and blipped the dce_v6 tube,
# glitch test 2026-08-12: --query=YES, --current=no). Prints
# "<name> <refresh>" (e.g. "640x480 60.00", current/preferred markers
# stripped). Optional $2="name" prints only the mode name. The xrandr
# exit code lies — the effective mode is truth.
# The compact listing shows a mode's refresh rates on ONE line
# ("640x480  75.00  60.00*") — the active rate is the field carrying the
# '*', which is NOT always field 2 (misread as 75.00 while 480i 60.00 was
# active, 2026-08-10, GTX 970 -> false 240p fallbacks). Scan the fields.
# X connector state from xrandr --current (glitch-free cached path):
# 1 = connected, 0 = disconnected, empty = output not listed. On NVIDIA the
# watcher's --query loop keeps this compiler-fresh for the analog ports (the
# only channel that reflects an NVIDIA replug).
_xrandr_connected() {
	xrandr --display "${DISPLAY:-:0}" --current 2>/dev/null | awk -v o="$1" '$1==o {print ($2=="connected" ? 1 : 0); exit}'
}

_xrandr_active_mode() {
	local out="$1" want="${2:-full}" mode
	mode=$(xrandr --display "${DISPLAY:-:0}" --current 2>/dev/null |
		sed -n "/^$out connected/,/^[^ ]/p" | grep '\*' | head -1 |
		awk '{ for (i = 2; i <= NF; i++) if ($i ~ /\*/) { gsub(/[*+]/, "", $i); print $1, $i; exit } }')
	[ -n "$mode" ] || return 1
	if [ "$want" = "name" ]; then
		echo "${mode%% *}"
	else
		echo "$mode"
	fi
}

# Primary output of the X screen (the batocera-resolution anchor,
# PSCREEN=$(xrandr --listPrimary), batocera-resolution:18). Parsed from
# xrandr --current ("DVI-I-1 connected primary ...") — glitch-free: the
# stock --listPrimary forces a connector re-probe that blips the dce_v6
# tube (glitch test 2026-08-12). Prints the output name or nothing.
_xrandr_primary() {
	xrandr --display "${DISPLAY:-:0}" --current 2>/dev/null |
		sed -n '/ connected primary /p' | head -1 | awk '{print $1}'
}

# Single helper for the universal --noprimary-first lesson (verified 2026-08-11
# Intel UHD 630 BadMatch when LCD held large mode): clears the current primary
# before a new --primary, no per-GPU branch, no framebuffer touch.
_primary_clear_for() {
	local want="$1" cur
	cur=$(_xrandr_primary 2>/dev/null)
	if [ -n "$cur" ] && [ "$cur" != "$want" ]; then
		xrandr --display "${DISPLAY:-:0}" --output "$cur" --noprimary 2>/dev/null || true
	fi
}

crt_probe() {
	export DISPLAY="${DISPLAY:-:0}"
	[ -n "$CRT_PRESUMED_OUTS" ] || return 0
	local out ok="" st
	for out in $CRT_PRESUMED_OUTS; do
		# Kernel truth only: a presumed port is a CRT when the kernel
		# reports it CONNECTED (real hotplug). A sysfs-disconnected port
		# stays PRESUMED — no modeset test (dce_v6 latch: empty-port
		# modesets succeed, and the probe's own modeset would create the
		# live-timing evidence the next detect reads to self-promote the
		# phantom, 2026-08-13). With an LCD, presumed+LCD = LCD-only
		# (this invariant is guard-tested).
		st="$(_sysfs_status "$out")"
		if [ "$st" = "connected" ]; then
			echo "CRT-DUAL-PROBE: $out — sysfs connected (REAL hotplug) -> CRT confirmed"
			ok="$ok $out"
		else
			echo "CRT-DUAL-PROBE: $out — sysfs ${st:-absent} (no real hotplug) -> NOT promoted, stays presumed; if the CRT is here: crt-dual.crt_output=$out in batocera.conf"
		fi
	done
	if [ -n "$ok" ]; then
		echo "$ok" | tr ' ' '\n' | grep -v '^$' >"$CRT_DUAL_STATE_DIR/probe-ok" 2>/dev/null || true # write may fail (full /tmp); detect_outputs re-reads absence as no promotion
	else
		rm -f "$CRT_DUAL_STATE_DIR/probe-ok" 2>/dev/null || true # rm -f is idempotent; no error if already absent
	fi
	return 0
}
