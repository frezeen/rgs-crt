# display-lib.sh — CRT-DUAL dual-output: detection + shared layout
#
# Centralizes video output classification (by CONNECTOR TYPE, never by port
# name) and the runtime dual-output layout. Single source shared by:
# - crt-x11-generator.sh  (per-output mapping in the X config, 99-crt.conf)
# - zz_crt_dual       (runtime layout at boot, layout_apply_if_changed)
#
# Exported variables (after detect_outputs):
# CRT_OUTS            — confirmed analog CRT outputs (connected, no EDID)
# CRT_PRESUMED_OUTS   — disconnected analog outputs (last resort; verified
# by crt_probe after X is up)
# LCD_OUTS            — digital outputs (native LCD), space-separated
# CRT_OUT             — first confirmed analog output (runtime layout)
# CRT_PRESUMED_OUT    — first presumed analog output
# LCD_OUT             — first digital output (runtime layout)
#
# Classification cascade (reliable signal -> presumption as LAST resort):
# digital connected -> LCD | analog + EDID -> LCD | analog connected
# without EDID -> CRT | analog disconnected -> CRT_PRESUMED (test = crt_probe).
#
# Prerequisite: detect_gpu (gpu-lib.sh) must have run before layout_apply_if_changed.
#
# Shell contract: this library is written to be safe under `set -u` and
# `set -o pipefail` (every possibly-unset variable has an explicit default,
# pipelines are failure-tolerant). The caller enables those options — a
# sourced library must NOT set shell options itself (they would mutate the
# caller's shell state; the generator does `set -uo pipefail` before sourcing).
#
# TUBE-SAFETY CONTRACT (why some things are deliberately non-obvious):
# - NEVER `--auto` on the CRT. The DP->VGA converter's fake EDID advertises
# VESA 31kHz modes (640x480@59.94 preferred); --auto would pick it and
# put the tube out of lock (risk of damage). 15kHz modes are set by name
# only (src/owner/sr-owner.sh _crt_set_15khz_direct).
# - 60.00 vs 59.94 matters: the refresh field distinguishes OUR 480i
# (60.00) from the VESA EDID 640x480@59.94 (31kHz). layout-watch uses it
# to detect a gameStop collision and restore the desktop mode.
# - `DefaultModes False` in the CRT Monitor section: suppress the builtin
# VESA modes (31kHz+) on EDID-less ports, so nothing can land 31kHz on
# the tube by accident.
# - 240p fallback on digital ports (converter): when 480i interlace is
# rejected (DP -> ENOENT), fall back to 320x240 + --scale 2x2 so the
# FULL 640x480 desktop stays visible at 240p.
# - gameStop guard: restore_after_game() re-applies the desktop layout
# after a CRT game; MODE_FILE marks an active game so the hotplug
# watcher skips mid-game layout changes.

# The 15kHz CRT mode is "640x480i" (480i), generated by SwitchRes from the
# system ini (/etc/switchres.ini) and written into 99-crt.conf by
# crt-x11-generator.sh. ONE 480i modeline, ONE unique name: the official
# Batocera interlace name "640x480i" (never the bare "640x480" — the kernel
# re-synthesizes its own "640x480" 54MHz DoubleScan / 25.175MHz @59.94 on
# the analog re-probe; a shared name made --mode nondeterministic and the
# tube went black at boot, verified 2026-08-12 AMD R9 270X).
# Scope: this name is the CONF/BOOT contract only (X attaches it itself at
# startup). Mode names are owned by their generator: at runtime the desktop
# is the engine-issued SR-* handle — no path requests "640x480i" by name
# (NVIDIA renames WxH-like conf names to the bare form and BadMatches their
# runtime re-add, verified 2026-08-28 GTX 970; the same literal that reads
# correctly on AMD aborts a whole batch client-side on NVIDIA).

# Classification by CONNECTOR TYPE (no hardcoded port names).
# Analog  -> 15kHz CRT:  DVI-I, VGA, CRT
# Digital -> native LCD: HDMI, DVI-D, DisplayPort, eDP
# NOTE: on NVIDIA sysfs exposes no EDID (0 bytes), but xrandr --prop does
# (verified live: HDMI-0 LCD exposes the EDID block, DVI-I-0 CRT does not).
# The base classification is by connector type; EDID (post-X) and the
# crt-dual.analog_lcd=1 override refine the LCD-on-analog-port case.
# A CRT on a pure digital port (DVI-D/HDMI/DP) cannot be auto-detected:
# it must be wired to the analog port (DVI-I/VGA).
# TEST SEAM: dry-run tests read the DRM connector tree from fixtures, never
# from the live box (tests/run.sh sets CRT_DUAL_SYSFS to a fixture tree;
# default = the kernel interface, so stock behavior is unchanged).
# Used by _detect_outputs_sysfs and _sysfs_status below.
CRT_DUAL_SYSFS="${CRT_DUAL_SYSFS:-/sys/class/drm}"

# ── GPU ADAPTER CONTRACT (2026-08-23) ─────────────────────────────
# Shared code NEVER branches on the GPU family for truth questions; it
# asks the ADAPTER (src/lib/gpu/<vendor>.sh, lazy-sourced once). Each
# adapter declares its ONE oracle per question in its header — NVIDIA is
# pure-X, AMD/Intel are sysfs-truth families with their documented
