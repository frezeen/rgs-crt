GPU_ADAPTER_FILE=""
_gpu_adapter() { # source the family adapter exactly once per process
	[ -n "${GPU_VENDOR:-}" ] || GPU_VENDOR="$(lspci 2>/dev/null | grep -qi nvidia && echo nvidia || echo generic)"
	local _f="$GPU_VENDOR"
	case "$_f" in amd | intel | nvidia) ;; *) _f=generic ;; esac
	_f="$LIB_DIR/gpu/$_f.sh"
	[ "$GPU_ADAPTER_FILE" = "$_f" ] && return 0
	if [ -f "$_f" ]; then
		# shellcheck disable=SC1090
		source "$_f" && GPU_ADAPTER_FILE="$_f"
	else
		source "$LIB_DIR/gpu/generic.sh" && GPU_ADAPTER_FILE="$LIB_DIR/gpu/generic.sh"
	fi
}
_EDID_PROPS_CACHE="" # adapter-owned --prop snapshot (refreshed per detect)

# Trampolines — stable shared API; the family adapter owns each answer.
_edid_present() { # <xout> -> 0|1 : EDID evidence per the family oracle
	_gpu_adapter || return 1
	_impl_edid "$1"
}
_mode_inject_default() { # index-form API create + RandR attach, with read-back verify
	# Source-confirmed (upstream master, custom_video_xrandr.cpp:470-536):
	# the xrandr backend selects a display ONLY if connected AND holding a
	# CRTC; a connected-but-modeless output is skipped -> "no screen
	# detected". Index-form binding passes "0" as the positional screen_pos
	# clause, so it binds the FIRST valid output (the LCD) instead - and X
	# user modes are SCREEN-GLOBAL, so the fresh SR-* mode lands in the
	# global mode space reachable by any output. The API stays the single
	# source of timing+name; one RandR --addmode attaches it to the TARGET
	# output - plumbing the library cannot cover for an output it did not
	# bind, never a second generator. Select-first still owns the mode:
	# next cycle re-certifies instead of re-injecting.
	local target="${1:-}" api out
	[ -z "$target" ] && return 1
	[ -n "${DISPLAY:-}" ] || export DISPLAY=:0
	api=$(_switchres_api_path)
	[ -r "$api" ] || return 1
	out=$(python3 "$api" create 640 480 "${CRT_DUAL_REFRESH:-60}" 0 --ini /etc/switchres.ini 2>/dev/null) || return 1
	case "$out" in SR-*) ;; *) return 1 ;; esac
	xrandr --addmode "$target" "$out" 2>/dev/null || return 1
	# read-back verify (no silent best-effort on a step the contract
	# depends on)
	xrandr --current 2>/dev/null | sed -n "/^$target connected/,/^[^ ]/p" | grep -q "$out" || return 1
	echo "$out"
}
_desktop_mode_name() {
	# Runtime NAME of the 15kHz desktop mode (the persistent conf
	# Modeline "640x480i") — a FAMILY fact, owned by the adapter:
	# modesetting keeps conf names verbatim ("640x480i"); NVIDIA presents
	# the same interlaced mode under the bare "640x480" alias and rejects
	# resolution-shaped suffixed re-adds (RRAddOutputMode BadMatch,
	# measured 2026-08-28 GTX 970). Shared code never hardcodes either.
	_gpu_adapter && _impl_desktop_mode_name
}
_crt_desktop_ensure() { # <out> -> echo the ATTACHABLE 480i desktop name for <out>
	# One resolution rule, all families (converges every boot topology to
	# the certified dual-boot flow): (1) the conf-family name when the
	# driver actually pooled it — every certified boot-time-connected flow
	# keeps its exact stream; (2) else the SR session mode the injector
	# created at bind — a late-plugged analog NEVER gets the conf mode
	# pooled (NVIDIA publishes conf modelines only for outputs connected
	# at X start; Xorg.0.log 12:33 boot 2026-08-30: MetaModes applied at
	# start on the disconnected port, mode absent from the pool after the
	# plug — dual restore/gameStart then died on "cannot find mode
	# 640x480"); (3) else ensure-inject (create+attach+read-back verify).
	# rc=1 loud when nothing is attachable — never a name fallback, never
	# a name literal in shared code (the conf name comes from the adapter
	# trampoline, the SR name from the shared injector).
	local target="$1" _pool _dn _sr
	[ -n "$target" ] || return 1
	[ -n "${DISPLAY:-}" ] || export DISPLAY=:0
	_pool=$(xrandr --current 2>/dev/null | sed -n "/^$target connected/,/^[^ ]/p")
	_dn=$(_desktop_mode_name 2>/dev/null)
	if [ -n "$_dn" ] && printf '%s\n' "$_pool" | grep -qE "(^|[[:space:]])${_dn}([[:space:]]|$)"; then
		echo "$_dn"
		return 0
	fi
	_sr=$(printf '%s\n' "$_pool" | grep -oE 'SR-[0-9]+_640x480@[0-9.]+i' | head -1)
	[ -n "$_sr" ] && { echo "$_sr"; return 0; }
	_mode_inject_default "$target"
}
_desktop_mode_spec() {
	# Echoes "NAME RATE" for the 15kHz desktop: NAME from the family
	# adapter (_desktop_mode_name), RATE from the DYNAMIC tube flag
	# crt-dual.refresh (60 NTSC / 50 PAL) — never hardcoded, read at call
	# time (universal-cross-gpu §3). One spec source for every apply path.
	local _dn _r
	_dn=$(_desktop_mode_name) || return 1
	_r=$(grep -E '^crt-dual\.refresh[[:space:]]*=' "$CRT_DUAL_BATOCERA_CONF" 2>/dev/null | tail -1 | sed 's/.*=//' | tr -d '[:space:]')
	[ -z "$_r" ] && _r=60
	echo "$_dn $_r"
}

